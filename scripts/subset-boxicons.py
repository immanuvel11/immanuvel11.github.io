"""Builds a tiny Boxicons subset (only the icons the site uses).

The full Boxicons font is ~115 KB (woff2) plus ~85 KB of CSS; the site uses
~40 glyphs. Run after adding a new icon:  python scripts/subset-boxicons.py
Needs:  pip install fonttools brotli   (and `npm install` for the boxicons package)
Boxicons by Atisa (boxicons.com) - font licensed CC BY 4.0, CSS MIT.
"""
import re
import subprocess
import sys
from pathlib import Path

BACKSLASH = chr(92)

root = Path(__file__).resolve().parent.parent
src = root / "src"
box = root / "node_modules" / "boxicons"
out_css = src / "styles" / "boxicons-subset.css"
out_font = src / "styles" / "fonts" / "boxicons-subset.woff2"

# Every icon class referenced anywhere in the source (incl. data files).
used = set()
for path in list(src.rglob("*.ts")) + list(src.rglob("*.tsx")) + [root / "index.html"]:
    used |= set(re.findall(r"\bbx[lsb]?-[a-z0-9-]+", path.read_text(encoding="utf-8")))

css = (box / "css" / "boxicons.css").read_text(encoding="utf-8")
rule = re.compile(r"\.(bx[lsb]?-[a-z0-9-]+):before\s*\{\s*content:\s*\"" + re.escape(BACKSLASH) + r"([0-9a-f]+)\"")
codes = dict(rule.findall(css))

missing = sorted(n for n in used if n not in codes)
if missing:
    sys.exit(f"Unknown icon classes (typo or not in Boxicons): {missing}")

chosen = {n: codes[n] for n in sorted(used)}
unicodes = ",".join(f"U+{c}" for c in chosen.values())
subprocess.run(
    [
        sys.executable, "-m", "fontTools.subset", str(box / "fonts" / "boxicons.ttf"),
        f"--unicodes={unicodes}", "--flavor=woff2", f"--output-file={out_font}",
        "--layout-features=", "--no-hinting", "--desubroutinize",
    ],
    check=True,
)

rules = "\n".join(f'.{n}:before {{ content: "{BACKSLASH}{c}"; }}' for n, c in chosen.items())
header = (
    "/* Generated by scripts/subset-boxicons.py - do not edit by hand.\n"
    f"   Boxicons (boxicons.com) subset to the {len(chosen)} icons used by this site. */\n"
)
base = """@font-face {
  font-family: "boxicons";
  font-weight: normal;
  font-style: normal;
  font-display: swap;
  src: url("./fonts/boxicons-subset.woff2") format("woff2");
}

.bx {
  font-family: "boxicons" !important;
  font-weight: normal;
  font-style: normal;
  font-variant: normal;
  line-height: 1;
  text-rendering: auto;
  display: inline-block;
  text-transform: none;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}
"""
out_css.write_text(header + base + "\n" + rules + "\n", encoding="utf-8")
print(f"{len(chosen)} icons -> {out_font.stat().st_size} bytes woff2")
